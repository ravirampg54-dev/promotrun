import { useState } from 'react';
import { Link } from 'react-router-dom';
import { Bell, CheckCheck, Trash2 } from 'lucide-react';
import { useStore } from '@/store/store';
import { useDerived, levelClasses, unreadCount } from '@/store/selectors';
import { Button } from '@/components/ui/Button';
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogTrigger } from '@/components/ui/Dialog';
import { EmptyState } from '@/components/ui/primitives';
import { cn } from '@/lib/utils';

export function NotificationCenter() {
  const [open, setOpen] = useState(false);
  const notifications = useStore((s) => s.notifications);
  const markRead = useStore((s) => s.markNotificationRead);
  const markAll = useStore((s) => s.markAllNotificationsRead);
  const clear = useStore((s) => s.clearNotifications);
  const derived = useDerived();
  const unread = unreadCount(notifications);

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger asChild>
        <Button variant="ghost" size="icon" className="relative" aria-label={`Notifications${unread ? `, ${unread} unread` : ''}`}>
          <Bell className="size-5" />
          {unread > 0 ? (
            <span className="absolute right-1.5 top-1.5 flex size-4 items-center justify-center rounded-full bg-status-red text-[9px] font-bold text-background tnum">
              {unread > 9 ? '9+' : unread}
            </span>
          ) : null}
        </Button>
      </DialogTrigger>
      <DialogContent className="max-w-md">
        <DialogHeader>
          <DialogTitle>What changed</DialogTitle>
          <p className="text-sm text-muted-foreground">
            Warnings are generated by the engine and only appear once.
          </p>
        </DialogHeader>

        <div className="flex items-center gap-2">
          <Button size="sm" variant="subtle" onClick={markAll} disabled={unread === 0}>
            <CheckCheck className="size-3.5" /> Mark all read
          </Button>
          <Button size="sm" variant="ghost" onClick={clear} disabled={notifications.length === 0}>
            <Trash2 className="size-3.5" /> Clear
          </Button>
        </div>

        {notifications.length === 0 ? (
          <EmptyState
            title="Nothing needs your attention"
            body={`${derived.risk.headline} Warnings show up here when a number changes.`}
          />
        ) : (
          <ul className="flex max-h-[50vh] flex-col gap-2 overflow-y-auto">
            {notifications.map((n) => {
              const styles = levelClasses(n.level);
              return (
                <li key={n.id}>
                  <button
                    type="button"
                    onClick={() => markRead(n.id)}
                    className={cn(
                      'flex w-full flex-col gap-1 rounded-lg border p-3 text-left transition-colors hover:bg-surface-2',
                      !n.read && styles.border,
                    )}
                  >
                    <span className="flex items-center gap-2">
                      <span className={cn('size-1.5 rounded-full', styles.dot)} aria-hidden />
                      <span className={cn('text-sm font-bold', styles.text)}>{n.title}</span>
                      {!n.read ? <span className="ml-auto text-[10px] font-bold uppercase text-muted-foreground">new</span> : null}
                    </span>
                    <span className="text-xs text-muted-foreground">{n.body}</span>
                  </button>
                </li>
              );
            })}
          </ul>
        )}

        <Button asChild variant="outline" size="sm" className="w-full">
          <Link to="/health">Open financial health</Link>
        </Button>
      </DialogContent>
    </Dialog>
  );
}